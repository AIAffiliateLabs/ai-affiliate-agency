def _validate_public_http_url(url: str):
    """Allow only public HTTP(S) destinations; block local/private targets."""
    parsed = urlparse(url)

    if parsed.scheme not in ("http", "https") or not parsed.hostname:
        raise ValueError("Only public HTTP/HTTPS URLs are allowed.")

    host = parsed.hostname.lower().rstrip(".")
    if host in {"localhost", "localhost.localdomain"} or host.endswith(".local"):
        raise ValueError("Local hostnames are not allowed.")

    try:
        addresses = socket.getaddrinfo(host, parsed.port or (443 if parsed.scheme == "https" else 80))
    except socket.gaierror as exc:
        raise ValueError("Hostname could not be resolved.") from exc

    if not addresses:
        raise ValueError("Hostname has no public address.")

    for address in addresses:
        ip = ipaddress.ip_address(address[4][0].split("%")[0])
        if not ip.is_global:
            raise ValueError("Private, reserved or non-public IP destinations are blocked.")

    return parsed


class _SafeRedirectHandler(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        absolute = urljoin(req.full_url, newurl)
        _validate_public_http_url(absolute)
        return super().redirect_request(req, fp, code, msg, headers, absolute)


class _PageParser(HTMLParser):
    """Small HTML parser that captures visible text and common page metadata."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.title_parts = []
        self.h1_parts = []
        self.text_parts = []
        self.links = []
        self.in_title = False
        self.in_h1 = False
        self.skip_depth = 0
        self.meta_description = ""
        self.og_title = ""
        self.og_description = ""

    def handle_starttag(self, tag, attrs):
        attrs = {str(k).lower(): v for k, v in attrs}
        tag = str(tag).lower()
        if tag == "title":
            self.in_title = True
        elif tag == "h1" and not self.h1_parts:
            self.in_h1 = True
        if tag in ("script", "style", "noscript", "svg"):
            self.skip_depth += 1
        if tag == "meta":
            name = str(attrs.get("name", "") or "").lower()
            prop = str(attrs.get("property", "") or "").lower()
            value = str(attrs.get("content", "") or "").strip()
            if name == "description" and value:
                self.meta_description = value
            elif prop == "og:title" and value:
                self.og_title = value
            elif prop == "og:description" and value:
                self.og_description = value
            elif name == "twitter:title" and value and not self.og_title:
                self.og_title = value
            elif name == "twitter:description" and value and not self.og_description:
                self.og_description = value
        if tag == "a" and attrs.get("href"):
            self.links.append((attrs["href"], attrs.get("aria-label", "")))

    def handle_endtag(self, tag):
        tag = str(tag).lower()
        if tag == "title":
            self.in_title = False
        elif tag == "h1":
            self.in_h1 = False
        if tag in ("script", "style", "noscript", "svg") and self.skip_depth:
            self.skip_depth -= 1

    def handle_data(self, data):
        if self.skip_depth:
            return
        clean = " ".join(data.split())
        if not clean:
            return
        if self.in_title:
            self.title_parts.append(clean)
        if self.in_h1:
            self.h1_parts.append(clean)
        self.text_parts.append(clean)



def _fallback_title_from_url(url, h1=""):
    """Create a descriptive label from captured page structure/URL, not invented facts."""
    if str(h1 or "").strip():
        return re.sub(r"\s+", " ", str(h1)).strip()[:250]
    parsed = urlparse(str(url or ""))
    host = (parsed.hostname or "").split(":", 1)[0]
    brand = host.split(".")[0].replace("-", " ").title() if host else "Website"
    path_parts = [part for part in (parsed.path or "").split("/") if part]
    if not path_parts:
        return brand
    last = path_parts[-1].replace("-", " ").replace("_", " ").strip().title()
    if last in {"Affiliates", "Affiliate"} or (len(path_parts) > 1 and path_parts[-2].casefold() == "partners"):
        last = "Affiliate Program"
    if last.casefold() == "signup":
        last = "Affiliate Signup"
    return f"{brand} — {last}"[:250]


def _fallback_description_from_text(page_text, h1=""):
    """Summarize only captured visible text when HTML description metadata is absent."""
    text = re.sub(r"\s+", " ", str(page_text or "")).strip()
    if not text:
        return ""
    if h1:
        position = text.casefold().find(str(h1).casefold())
        if position >= 0:
            text = text[position + len(str(h1)):].strip(" :-–—|")
    # Avoid using a site navigation string as a fabricated description.
    for marker in ("Skip to content", "Skip to main content"):
        if text.casefold().startswith(marker.casefold()):
            return ""
    if len(text) < 45:
        return ""
    return text[:360].rsplit(" ", 1)[0].rstrip(" ,;:")


def inspect_public_page(url: str):
    """Fetch a small amount of public HTML without executing scripts."""
    try:
        _validate_public_http_url(url)
        request = Request(
            url,
            headers={
                "User-Agent": "AffiliateIntelligenceResearchBot/1.0 (+public-page-inspection)",
                "Accept": "text/html,application/xhtml+xml"
            }
        )
        opener = build_opener(_SafeRedirectHandler())
        with opener.open(request, timeout=PAGE_TIMEOUT_SECONDS) as response:
            final_url = response.geturl()
            _validate_public_http_url(final_url)
            content_type = response.headers.get("Content-Type", "").lower()
            if "html" not in content_type and "xhtml" not in content_type:
                return {
                    "requested_url": url,
                    "final_url": final_url,
                    "status": "skipped_non_html",
                    "reason": "Response was not HTML."
                }
            raw = response.read(MAX_PAGE_BYTES + 1)
            if len(raw) > MAX_PAGE_BYTES:
                raw = raw[:MAX_PAGE_BYTES]
            charset = response.headers.get_content_charset() or "utf-8"
            html = raw.decode(charset, errors="replace")

        parser = _PageParser()
        parser.feed(html)
        page_text = re.sub(r"\s+", " ", " ".join(parser.text_parts)).strip()
        captured_h1 = re.sub(r"\s+", " ", " ".join(parser.h1_parts)).strip()
        raw_title = " ".join(parser.title_parts).strip()
        raw_description = parser.meta_description.strip()
        title = raw_title or parser.og_title.strip() or _fallback_title_from_url(final_url, captured_h1)
        description = raw_description or parser.og_description.strip()
        description_source = "html_meta_description" if raw_description else (
            "open_graph_description" if parser.og_description.strip() else "not_available"
        )
        if not description:
            description = _fallback_description_from_text(page_text, captured_h1)
            if description:
                description_source = "captured_visible_text_fallback_not_html_metadata"
        title_source = "html_title" if raw_title else (
            "open_graph_title" if parser.og_title.strip() else (
                "captured_h1" if captured_h1 else "url_path_fallback"
            )
        )
        return {
            "requested_url": url,
            "final_url": final_url,
            "status": "inspected",
            "title": title[:250],
            "title_source": title_source,
            "h1": captured_h1[:250],
            "description": description[:500],
            "description_source": description_source,
            "text_excerpt": page_text[:6500],
            "links": parser.links[:250]
        }
    except Exception as exc:
        return {
            "requested_url": url,
            "status": "fetch_failed",
            "reason": str(exc)[:300]
        }


def collect_official_site_evidence(search_results):
    """Inspect candidate-specific search pages first, then a small general fallback."""
    inspected = []
    seen = set()
    candidates = []

    # Candidate-specific results are passed first by the workflow.
    for item in search_results:
        url = item.get("url")
        if not url or url in seen:
            continue
        seen.add(url)
        candidates.append({"url": url, "candidate": item.get("candidate", "Unassigned")})
        if len(candidates) >= 40:
            break

    for item in candidates:
        page = inspect_public_page(item["url"])
        page["candidate"] = item["candidate"]
        inspected.append(page)

    affiliate_candidates = []
    for page in inspected:
        if page.get("status") != "inspected":
            continue
        base = page.get("final_url") or page.get("requested_url")
        base_host = urlparse(base).hostname
        for href, anchor in page.get("links", []):
            combined = f"{href} {anchor}".lower()
            if any(term in combined for term in AFFILIATE_TERMS):
                candidate = urljoin(base, href)
                if urlparse(candidate).hostname == base_host and candidate not in seen:
                    seen.add(candidate)
                    affiliate_candidates.append({
                        "url": candidate,
                        "candidate": page.get("candidate", "Unassigned")
                    })

    # Inspect a bounded number of affiliate/partner links on the same host.
    for item in affiliate_candidates[:15]:
        page = inspect_public_page(item["url"])
        page["candidate"] = item["candidate"]
        inspected.append(page)

    compact = []
    for page in inspected:
        item = dict(page)
        # Retain affiliate/application-related links discovered on the candidate page for traceable URL extraction.
        base = item.get("final_url") or item.get("requested_url") or ""
        base_host = urlparse(base).hostname
        relevant_links = []
        for href, anchor in item.get("links", []):
            absolute = urljoin(base, href)
            label_and_url = f"{anchor} {absolute}".lower()
            is_http = urlparse(absolute).scheme in ("http", "https")
            has_program_context = any(term in label_and_url for term in AFFILIATE_TERMS + ("apply", "sign up", "join", "register"))
            # Retain external application portals only when linked from a candidate-host page
            # with an explicit affiliate/application cue; never label them as official domains.
            if is_http and has_program_context:
                relevant_links.append({
                    "url": absolute,
                    "anchor_text": anchor[:180],
                    "linked_from_candidate_host_url": base,
                    "link_host_matches_candidate_page": urlparse(absolute).hostname == base_host
                })
        item["relevant_program_links"] = relevant_links[:60]
        item.pop("links", None)
        compact.append(item)

    return {
        "checked_at_utc": datetime.now(timezone.utc).isoformat(),
        "pages_inspected": len(compact),
        "pages": compact
    }


