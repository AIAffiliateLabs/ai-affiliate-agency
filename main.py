def _validate_user_tracking_url(raw_url):
    """Validate syntax only; do not fetch or claim that a supplied tracking URL works."""
    value = str(raw_url or "").strip()
    if not value:
        return ""
    parsed = urlparse(value)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
        raise HTTPException(status_code=422, detail="affiliate_tracking_url must be a complete HTTPS URL without embedded credentials.")
    if any(ch.isspace() for ch in value):
        raise HTTPException(status_code=422, detail="affiliate_tracking_url cannot contain whitespace.")
    return value


def extract_seo_package(content, primary_keyword=""):
    """Extract SEO metadata from common labels without inventing missing values."""
    text = str(content or "")
    labels = {
        "seo_title": ("SEO title", "Suggested Meta Title", "Meta Title", "SEO Title"),
        "meta_description": ("Meta description", "Suggested Meta Description", "Meta Description"),
        "url_slug": ("URL slug", "Suggested URL Slug", "Slug"),
        "search_intent": ("Search intent", "Search Intent"),
        "secondary_keywords": ("Secondary keywords", "Secondary Keywords"),
        "primary_keyword": ("Primary keyword", "Primary SEO Keyword")
    }
    extracted = {}
    for field, variants in labels.items():
        value = ""
        for label in variants:
            match = re.search(
                rf"(?im)^\s*(?:[-*]\s*)?(?:\*\*)?{re.escape(label)}(?:\*\*)?\s*:\s*(.+?)\s*$",
                text
            )
            if match:
                value = match.group(1).strip()
                value = re.sub(r"^\*\*\s*", "", value)
                value = re.sub(r"\s*\*\*$", "", value)
                value = value.strip().strip('`"\'')
                break
        extracted[field] = value
    # Deterministic fallbacks use only text already present in the generated draft.
    # They do not introduce product facts or claim keyword research was performed.
    if not extracted["seo_title"]:
        h1 = re.search(r"(?m)^#\s+(.+?)\s*$", text)
        if h1:
            extracted["seo_title"] = h1.group(1).strip()
    if not extracted["meta_description"]:
        paragraphs = re.split(r"\n\s*\n", text)
        for paragraph in paragraphs:
            cleaned = re.sub(r"(?m)^#{1,6}\s+", "", paragraph).strip()
            cleaned = re.sub(r"\s+", " ", cleaned)
            if len(cleaned) >= 60 and not cleaned.startswith(("- ", "* ", "A.", "B.", "C.")):
                # Prefer an introductory paragraph; cap to standard snippet length.
                if len(cleaned) > 160:
                    excerpt = cleaned[:157].rsplit(" ", 1)[0].rstrip(" ,;:")
                    extracted["meta_description"] = excerpt + "..."
                else:
                    extracted["meta_description"] = cleaned
                break
    if not extracted["url_slug"] and extracted["seo_title"]:
        slug = re.sub(r"[^a-z0-9]+", "-", extracted["seo_title"].casefold()).strip("-")
        extracted["url_slug"] = slug[:100].strip("-")
    if not extracted["search_intent"] and extracted["seo_title"]:
        extracted["search_intent"] = "Informational (inferred from requested content type; not keyword research)"
    if primary_keyword:
        extracted["primary_keyword"] = str(primary_keyword).strip()
    return extracted


def sanitize_seo_metadata(meta_description, candidate, quality_control, semantic_review, candidate_record):
    """Remove unsupported certainty/affiliate-term language from SEO metadata.

    SEO snippets are public-facing claims too. A non-empty Ledger field or an
    AI-supported semantic verdict is not sufficient to call an affiliate term
    verified. Keep a neutral description whenever evidence or review is open.
    """
    meta = re.sub(r"\s+", " ", str(meta_description or "")).strip()
    blocked = int((quality_control or {}).get("claims_blocked", 0) or 0) > 0
    verdicts = (semantic_review or {}).get("verdict_counts", {})
    semantic_open = bool(verdicts.get("unclear", 0) or verdicts.get("contradicted", 0))
    verification_status = str((candidate_record or {}).get("verification_status", "Not verified")).strip().casefold()
    ledger_not_verified = verification_status not in {"verified", "fully verified", "confirmed"}
    certainty_language = bool(re.search(r"\bverified\b|\bconfirmed\b|\bguaranteed\b", meta, re.I))
    affiliate_term_language = bool(re.search(
        r"\b(?:commission|commissions|cookie|payout|affiliate program|partner program|recurring)\b", meta, re.I
    ))
    needs_neutral_copy = certainty_language or blocked or semantic_open or (ledger_not_verified and affiliate_term_language)
    if needs_neutral_copy:
        safe_candidate = str(candidate or "the product").strip()
        meta = (
            f"Explore {safe_candidate}'s product information and review publisher-program terms "
            "directly with the provider before making a decision."
        )
    # Hard safety net: never return a snippet that still claims verification
    # when the evidence gate or semantic review is unresolved.
    if (blocked or semantic_open or ledger_not_verified) and re.search(r"\bverified\b", meta, re.I):
        meta = f"Explore {str(candidate or 'the product').strip()} and confirm relevant details directly with the provider."
    if len(meta) > 160:
        return meta[:157].rsplit(" ", 1)[0].rstrip(" ,;:") + "..."
    return meta



def sanitize_seo_title(seo_title, candidate, source_content=""):
    """Keep a complete, natural SEO title within 30-60 characters.

    Character-count compliance alone is insufficient: an exactly-60-character
    title may have been cut in the middle of a phrase. Reject dangling or
    obviously incomplete endings and use a deterministic candidate-based title.
    """
    title = re.sub(r"\s+", " ", str(seo_title or "")).strip().strip('"\'')
    words = re.findall(r"[A-Za-z0-9]+", title)
    last_word = words[-1].casefold() if words else ""
    incomplete_endings = {
        "a", "an", "and", "or", "but", "the", "of", "for", "to", "with",
        "in", "on", "at", "by", "from", "as", "into", "break", "broken",
        "including", "featuring", "about", "vs"
    }
    dangling = (last_word in incomplete_endings) or bool(re.search(r"(?:[:|,;\-]|&)$", title))
    # Catch model/title-length truncation where the last SEO token is only a
    # prefix of the corresponding complete word in the article's H1.
    h1_match = re.search(r"(?m)^#\s+(.+?)\s*$", str(source_content or ""))
    h1_words = [word.casefold() for word in re.findall(r"[A-Za-z0-9]+", h1_match.group(1))] if h1_match else []
    seo_words = [word.casefold() for word in re.findall(r"[A-Za-z0-9]+", title)]
    truncated_word = False
    if seo_words and h1_words:
        last = seo_words[-1]
        truncated_word = any(word.startswith(last) and len(word) > len(last) for word in h1_words)
    valid_length = 30 <= len(title) <= 60
    if title and valid_length and not dangling and not truncated_word:
        return title

    name = re.sub(r"\s+", " ", str(candidate or "Product")).strip()
    candidates = [
        f"{name} Review: Features, Pricing & Key Details",
        f"{name} Review: Features & Pricing",
        f"{name} Review: Key Features and Pricing",
        f"{name} Review: An Overview",
    ]
    for candidate_title in candidates:
        if 30 <= len(candidate_title) <= 60:
            return candidate_title

    # Long merchant names: shorten only at a word boundary, preserving a complete suffix.
    suffix = " Review: Key Details"
    max_name = max(1, 60 - len(suffix))
    shortened_name = name[:max_name].rsplit(" ", 1)[0].strip() or name[:max_name].strip()
    fallback = f"{shortened_name}{suffix}"
    if len(fallback) < 30:
        fallback = f"{shortened_name} Review: Features"
    return fallback[:60].rstrip(" ,:;|- ")


def build_seo_quality_check(content, primary_keyword=""):
    """Check SEO package presence and basic formatting; not ranking potential."""
    package = extract_seo_package(content, primary_keyword)
    seo_title = package["seo_title"]
    meta = package["meta_description"]
    slug = package["url_slug"]
    keyword = package["primary_keyword"]
    h1_count = len(re.findall(r"(?m)^#\s+\S", str(content or "")))
    checks = {
        "seo_title_present": bool(seo_title),
        "seo_title_length_30_to_60": bool(seo_title) and 30 <= len(seo_title) <= 60,
        "meta_description_present": bool(meta),
        "meta_description_at_most_160_chars": bool(meta) and len(meta) <= 160,
        "url_slug_present": bool(slug),
        "primary_keyword_present": bool(keyword),
        "primary_keyword_in_title": bool(keyword and seo_title and keyword.casefold() in seo_title.casefold()),
        "one_or_more_h1_headings": h1_count >= 1
    }
    return {
        "status": "format_checks_passed" if all(checks.values()) else "review_required",
        "primary_keyword": keyword or "Not supplied",
        "seo_title": seo_title or "Not detected",
        "seo_title_characters": len(seo_title),
        "meta_description": meta or "Not detected",
        "meta_description_characters": len(meta),
        "url_slug": slug or "Not detected",
        "search_intent": package["search_intent"] or "Not detected",
        "secondary_keywords": package["secondary_keywords"] or "Not detected",
        "h1_heading_count": h1_count,
        "checks": checks,
        "limitation": "These are formatting and presence checks only. They do not guarantee search rankings, search volume, keyword difficulty, traffic or SEO performance."
    }


