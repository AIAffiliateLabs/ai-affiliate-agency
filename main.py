def _host(url):
    try:
        return (urlparse(url).hostname or "").lower().removeprefix("www.")
    except Exception:
        return ""


def _candidate_key(name):
    return re.sub(r"[^a-z0-9]", "", (name or "").lower())


def _page_text(page):
    return " ".join([
        page.get("title", ""),
        page.get("description", ""),
        page.get("text_excerpt", "")
    ]).lower()


def _candidate_page_match(candidate_name, page):
    """Conservative association: candidate metadata must match, then host/title evidence."""
    if page.get("candidate", "").strip().lower() != candidate_name.strip().lower():
        return False
    key = _candidate_key(candidate_name)
    host = _candidate_key(_host(page.get("final_url") or page.get("requested_url", "")))
    title = _candidate_key(page.get("title", ""))
    # Require a recognizable brand token in either host or page title.
    return bool(key and (key in host or key in title))


def _commission_percentage_from_sentence(sentence):
    """Return a percentage only when grammar directly ties it to commission."""
    text = re.sub(r"\s+", " ", sentence or "").strip()
    percent = r"(\d{1,3}(?:\.\d{1,2})?\s*%)"
    patterns = [
        # "20% commission", "20% recurring commission", "20% affiliate commission"
        rf"{percent}\s*(?:(?:recurring|affiliate|referral)\s+)?commissions?\b",
        # "commission of 20%", "commission rate is 20%"
        rf"\bcommissions?\s*(?:rate\s*)?(?:of|is|:|at)\s*{percent}",
        # "earn 20% commission", "earn a 20% recurring commission"
        rf"\b(?:earn|earns|receive|receives|paid|pays?)\s+(?:a\s+)?(?:up\s+to\s+)?{percent}\s*(?:(?:recurring|affiliate|referral)\s+)?commissions?\b",
        # "earn commission of 20%"
        rf"\b(?:earn|earns|receive|receives|paid|pays?)\s+(?:a\s+)?(?:recurring\s+)?commissions?\s*(?:of|at)\s*{percent}",
    ]
    for pattern in patterns:
        match = re.search(pattern, text, re.IGNORECASE)
        if match:
            # The first capture in the first pattern is nested; use the final captured value.
            value = match.groups()[-1]
            return re.sub(r"\s+", "", value)
    return None


def _extract_duration_value(text):
    """Parse common duration formats, including hyphenated forms such as 30-day."""
    match = re.search(
        r"(?i)\b(\d{1,4})\s*[- ]?\s*(days?|weeks?|months?)\b",
        str(text or "")
    )
    if not match:
        return None
    amount = int(match.group(1))
    unit = match.group(2).lower()
    # Store normalized plural units so equivalent forms compare consistently.
    unit = {"day": "days", "days": "days", "week": "weeks", "weeks": "weeks",
            "month": "months", "months": "months"}[unit]
    return f"{amount} {unit}"


def _extract_explicit_terms(text):
    """Extract numeric terms only when the sentence semantically connects value and term."""
    commission = "Not verified"
    cookie = "Not verified"
    evidence = []
    normalized = re.sub(r"\s+", " ", text or "")
    # Split into sentence-like units to avoid borrowing unrelated page numbers.
    chunks = re.split(r"(?<=[.!?;])\s+|\n+", normalized)
    for chunk in chunks:
        sentence = chunk.strip()
        if not sentence or len(sentence) > 500:
            continue
        if commission == "Not verified":
            commission_value = _commission_percentage_from_sentence(sentence)
            if commission_value:
                commission = commission_value
                evidence.append({"term": "commission", "value": commission, "excerpt": sentence[:350]})
        if cookie == "Not verified" and re.search(r"(?i)\bcookies?\b", sentence):
            duration_value = _extract_duration_value(sentence)
            if duration_value:
                cookie = duration_value
                evidence.append({"term": "cookie_duration", "value": cookie, "excerpt": sentence[:350]})
        if commission != "Not verified" and cookie != "Not verified":
            break
    return commission, cookie, evidence


def _classify_program_type(pages):
    """Conservative classification; partner language alone is not an affiliate program."""
    text = " ".join(_page_text(page) for page in pages).lower()
    if any(x in text for x in ("affiliate program", "affiliate programme", "become an affiliate", "publisher program", "referral commission")):
        return "Classic affiliate/referral program — evidence language observed"
    if any(x in text for x in ("agency partner", "technology partner", "solution partner", "reseller partner", "integration partner", "partner directory")):
        return "B2B/agency/technology partnership — not confirmed as a publisher affiliate program"
    if any(x in text for x in ("partner program", "partner programme", "partners")):
        return "Partner program — type unclear; classic affiliate status not established"
    return "Unclear / no program type established"


def _candidate_host_match(candidate_name, page):
    """Require candidate identity in the fetched hostname; page titles alone are insufficient."""
    candidate_key = _candidate_key(candidate_name)
    host_key = _candidate_key(_host(page.get("final_url") or page.get("requested_url", "")))
    return bool(candidate_key and host_key and (candidate_key in host_key or host_key in candidate_key))


def _is_publisher_program_page(page):
    """Only explicit publisher-facing affiliate/referral language qualifies."""
    text = _page_text(page)
    url = (page.get("final_url") or page.get("requested_url", "")).lower()
    combined = f"{text} {url}"
    explicit = (
        "affiliate program", "affiliate programme", "become an affiliate",
        "join our affiliate", "affiliate application", "publisher program",
        "publisher programme", "referral program", "referral programme",
        "referral commission", "earn commission as an affiliate",
        "affiliate partners"
    )
    b2b_only = (
        "agency partner", "technology partner", "solution partner",
        "reseller partner", "integration partner", "implementation partner"
    )
    if any(term in combined for term in b2b_only) and not any(term in combined for term in explicit):
        return False
    return any(term in combined for term in explicit)


def _is_b2b_partner_page(page):
    combined = _page_text(page) + " " + (page.get("final_url") or page.get("requested_url", "")).lower()
    return any(term in combined for term in (
        "agency partner", "technology partner", "solution partner",
        "reseller partner", "integration partner", "implementation partner"
    ))


def _unique_nonempty(values):
    return list(dict.fromkeys(v for v in values if isinstance(v, str) and v.strip()))


def _is_application_url(url, anchor=""):
    """Accept only affiliate-specific application routes, not generic signups.

    A network hostname alone is insufficient. Network destinations require an
    explicit affiliate/referral/publisher cue in the link text or URL path.
    Generic merchant signup, agency onboarding, and unrelated regulatory links
    are deliberately excluded.
    """
    try:
        parsed = urlparse(str(url or ""))
        host = (parsed.hostname or "").lower()
        path = (parsed.path or "").lower()
    except Exception:
        return False
    if parsed.scheme not in ("http", "https") or not host:
        return False

    text = f"{url} {anchor}".lower()
    reject_terms = (
        "agency", "agencies", "solution partner", "technology partner",
        "integration partner", "reseller", "merchant signup", "store signup",
        "admin.shopify.com/signup", "federalregister.gov", "joinhoney.com"
    )
    if any(term in text for term in reject_terms):
        return False

    affiliate_terms = (
        "affiliate", "affiliates", "referral", "publisher", "creator affiliate",
        "affiliate partner", "affiliate program", "affiliate application"
    )
    has_affiliate_context = any(term in text for term in affiliate_terms)
    if not has_affiliate_context:
        return False

    # Require a meaningful affiliate/referral route or a recognized affiliate
    # network destination paired with explicit affiliate wording.
    route_terms = ("affiliate", "referral", "publisher", "partner-program", "partner_program")
    network_hosts = (
        "partnerstack.com", "impact.com", "cj.com", "awin.com",
        "shareasale.com", "rakutenadvertising.com", "avantlink.com"
    )
    path_is_specific = any(term in path for term in route_terms)
    is_network = any(host == domain or host.endswith("." + domain) for domain in network_hosts)
    return path_is_specific or is_network


def build_readiness_assessment(record):
    """Transparent deterministic readiness scores; not a prediction of approval or earnings."""
    status = record.get("verification_status", "")
    program_found = status == "Candidate-host affiliate/referral page inspected — program evidence found"
    discontinued = status == "Program discontinued — do not promote"
    direct_urls = record.get("official_program_urls", [])
    commission_known = record.get("commission") not in (None, "", "Not verified")
    cookie_known = record.get("cookie_duration") not in (None, "", "Not verified")
    eligibility_known = record.get("eligibility") not in (None, "", "Not verified")
    payout_known = record.get("payout_threshold") not in (None, "", "Not verified")
    application_text = record.get("application_status", "Not verified").lower()
    application_observed = any(x in application_text for x in ("application link", "apply", "sign up", "invitation"))
    ownership_authenticated = record.get("official_domain_confidence") == "Authenticated"

    # 100-point application readiness: evidence and actionable application route first,
    # then commercial terms and eligibility. Unknown fields score zero, never assumed.
    components = {
        "publisher_program_evidence": 25 if program_found else 0,
        "direct_program_url": 15 if direct_urls else 0,
        "commission_terms": 15 if commission_known else 0,
        "cookie_terms": 10 if cookie_known else 0,
        "geographic_eligibility": 10 if eligibility_known else 0,
        "payout_threshold": 10 if payout_known else 0,
        "application_route": 10 if application_observed else 0,
        "domain_ownership": 5 if ownership_authenticated else 0
    }
    application_score = 0 if (discontinued or not program_found) else sum(components.values())

    commercial_components = {
        "commission_terms": 35 if commission_known else 0,
        "cookie_terms": 20 if cookie_known else 0,
        "geographic_eligibility": 20 if eligibility_known else 0,
        "payout_threshold": 15 if payout_known else 0,
        "application_route": 10 if application_observed else 0
    }
    commercial_score = 0 if (discontinued or not program_found) else sum(commercial_components.values())

    if discontinued:
        label = "Disqualified — program discontinued"
    elif not program_found:
        label = "Research only — publisher program not established"
    elif application_score >= 80:
        label = "High readiness — manual confirmation still required"
    elif application_score >= 55:
        label = "Moderate readiness — resolve remaining unknowns"
    else:
        label = "Early lead — further verification required"

    missing = []
    for field, known in (
        ("commission", commission_known), ("cookie_duration", cookie_known),
        ("eligibility", eligibility_known), ("payout_threshold", payout_known),
        ("application route", bool(direct_urls) or application_observed),
        ("legal domain ownership", ownership_authenticated)
    ):
        if not known:
            missing.append(field)

    return {
        "application_readiness_score": application_score,
        "commercial_readiness_score": commercial_score,
        "readiness_label": label,
        "score_components": components,
        "commercial_score_components": commercial_components,
        "missing_items": missing,
        "interpretation": "Deterministic evidence-completeness score only. It is not an approval probability, revenue forecast, or guarantee that applications are open. Unknown fields score zero and are not inferred."
    }


