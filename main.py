def enrich_candidate_record_from_site_scan(candidate_record, site_scan):
    """Add exact terms from scanned candidate-host pages without claiming legal authentication."""
    enriched = copy.deepcopy(candidate_record or {})
    pages = (site_scan or {}).get("pages", []) if isinstance(site_scan, dict) else []
    existing = list(enriched.get("term_evidence") or [])
    seen = {
        (item.get("term"), str(item.get("value", "")).casefold(), item.get("evidence_url"))
        for item in existing if isinstance(item, dict)
    }
    official_host = _host(enriched.get("official_url_candidate", ""))
    program_pages = []
    for page in pages:
        if not isinstance(page, dict) or page.get("status") != "inspected":
            continue
        if str(page.get("candidate", "")).strip().casefold() != str(enriched.get("candidate", "")).strip().casefold():
            continue
        if not _candidate_host_match(enriched.get("candidate", ""), page):
            continue
        page_url = page.get("final_url") or page.get("requested_url") or ""
        if not page_url or (official_host and _host(page_url) != official_host):
            continue
        page_text = _page_text(page)
        if not _is_publisher_program_page(page):
            continue
        program_pages.append(page)
        commission, cookie, terms = _extract_explicit_terms(page_text)
        commission_period, commission_excerpt = _extract_commission_duration_evidence(page_text)
        payout, payout_excerpt = _extract_payout_threshold_evidence(page_text)
        found = list(terms)
        if commission_period:
            found.append({"term": "commission_duration", "value": commission_period, "excerpt": commission_excerpt})
        if payout:
            found.append({"term": "payout_threshold", "value": payout, "excerpt": payout_excerpt})
        for item in found:
            item = dict(item)
            item["evidence_url"] = page_url
            item["source_authority"] = "captured candidate-host page; legal domain ownership not independently authenticated"
            key = (item.get("term"), str(item.get("value", "")).casefold(), page_url)
            if key not in seen:
                existing.append(item)
                seen.add(key)

        if enriched.get("commission") in (None, "", "Not verified") and commission != "Not verified":
            enriched["commission"] = commission
        if enriched.get("cookie_duration") in (None, "", "Not verified") and cookie != "Not verified":
            enriched["cookie_duration"] = cookie
        if enriched.get("commission_duration") in (None, "", "Not verified") and commission_period:
            enriched["commission_duration"] = commission_period
        if enriched.get("payout_threshold") in (None, "", "Not verified") and payout:
            enriched["payout_threshold"] = payout

    enriched["term_evidence"] = existing
    if program_pages:
        enriched["scanned_program_page_urls"] = list(dict.fromkeys(
            page.get("final_url") or page.get("requested_url") for page in program_pages
        ))
        enriched["term_evidence_provenance_status"] = "candidate_host_source_evidence_pending_human_confirmation"
        enriched["term_evidence_provenance_note"] = (
            "Exact terms were extracted from candidate-matched same-host public pages. "
            "This does not independently authenticate legal ownership or establish that terms remain current."
        )
    return enriched


def _is_partner_program_url(url):
    path = (urlparse(str(url or "")).path or "").casefold()
    return any(token in path for token in (
        "/affiliate", "/affiliates", "/partner", "/partnership", "/referral", "/ambassador"
    ))


def select_evidence_based_cta_urls(candidate, candidate_record, site_scan):
    """Choose only exact captured candidate-host URLs; never construct destinations."""
    pages = (site_scan or {}).get("pages", []) if isinstance(site_scan, dict) else []
    candidates = []
    partner_urls = []
    for page in pages:
        if not isinstance(page, dict) or page.get("status") != "inspected":
            continue
        if str(page.get("candidate", "")).strip().casefold() != str(candidate).strip().casefold():
            continue
        if not _candidate_host_match(candidate, page):
            continue
        url = _clean_url(page.get("final_url") or page.get("requested_url") or "")
        if not url:
            continue
        if _is_partner_program_url(url):
            partner_urls.append(url)
            continue
        path = (urlparse(url).path or "/").casefold()
        score = 0
        if path in {"", "/"}:
            score = 100
        elif "/features/" in path or "/platform" in path:
            score = 80
        elif "pricing" in path:
            score = 60
        elif any(term in path for term in ("/solutions/", "/product", "/tools/")):
            score = 50
        if score:
            candidates.append((score, len(path), url))

    candidates.sort(key=lambda item: (-item[0], item[1], item[2]))
    product_url = candidates[0][2] if candidates else ""
    partner_url = sorted(set(partner_urls), key=lambda url: (0 if "affiliate" in urlparse(url).path.casefold() else 1, len(url)))[0] if partner_urls else ""
    return {"product_url": product_url, "partner_program_url": partner_url}


def ensure_evidence_based_ctas(content, candidate, candidate_record, site_scan, tracking_url=""):
    """Add separate product and partner CTAs using URLs already captured in evidence."""
    text = str(content or "").strip()
    if not text:
        return text
    destinations = select_evidence_based_cta_urls(candidate, candidate_record, site_scan)
    product_url = destinations.get("product_url", "")
    partner_url = destinations.get("partner_program_url", "")

    # Correct misleading labels on already-present links to partner-program pages.
    def normalize_partner_label(match):
        label, url = match.group(1), _clean_url(match.group(2))
        if _is_partner_program_url(url) and not re.search(
            r"(?i)\b(?:affiliate|partner|publisher)\s+program\b|\bapply\s+as\s+an\s+affiliate\b|\bbecome\s+a\s+partner\b",
            label
        ):
            return f"[Review the {candidate} affiliate program]({url})"
        return match.group(0)

    text = _MARKDOWN_LINK_RE.sub(normalize_partner_label, text)
    known_links = {_clean_url(url) for _, url in _MARKDOWN_LINK_RE.findall(text)}
    additions = []

    effective_product_url = tracking_url or product_url
    if effective_product_url and effective_product_url not in known_links:
        if tracking_url:
            label = f"Visit {candidate} (tracking link supplied for human verification)"
        else:
            label = f"Explore {candidate}'s platform"
        additions.append(f"- [{label}]({effective_product_url})")

    if partner_url and partner_url not in known_links:
        additions.append(f"- [Review the {candidate} affiliate program]({partner_url})")

    if additions:
        text += "\n\n## Explore further\n\n" + "\n".join(additions)
    return _clean_public_markdown(text)


def collect_candidate_product_content_evidence(candidate, candidate_record, workflow, max_pages=8):
    """Fetch bounded, same-host product pages from a candidate-matched official domain.

    Search-result and third-party URLs are never used as crawl seeds. The seed must
    already be recorded as the candidate's official URL or as an inspected page
    whose hostname matches the candidate identity. This is source capture, not
    independent legal ownership verification.
    """
    if not isinstance(candidate_record, dict) or not isinstance(workflow, dict):
        return {"status": "not_run_invalid_evidence", "pages_inspected": 0, "pages": [], "note": "Candidate evidence was unavailable."}

    seed_urls = []
    official_candidate_url = candidate_record.get("official_url_candidate")
    if isinstance(official_candidate_url, str) and official_candidate_url.startswith(("http://", "https://")):
        seed_urls.append(official_candidate_url)

    existing_pages = (workflow.get("official_site_evidence") or {}).get("pages", [])
    for page in existing_pages:
        if not isinstance(page, dict) or page.get("status") != "inspected":
            continue
        if page.get("candidate", "").strip().casefold() != str(candidate).strip().casefold():
            continue
        if _candidate_host_match(candidate, page):
            seed = page.get("final_url") or page.get("requested_url")
            if seed:
                seed_urls.append(seed)

    seed_urls = list(dict.fromkeys(seed_urls))[:5]
    if not seed_urls:
        return {
            "status": "not_run_no_candidate_matched_official_domain",
            "pages_inspected": 0, "pages": [],
            "note": "No candidate-matched official-domain URL was available. Third-party pages were not crawled as official sources."
        }

    queue = list(seed_urls)
    queued = set(queue)
    visited = set()
    captured = []
    accepted_hosts = set()

    while queue and len(captured) < max_pages:
        url = queue.pop(0)
        if url in visited:
            continue
        visited.add(url)
        page = inspect_public_page(url)
        if page.get("status") != "inspected":
            continue
        if not _candidate_host_match(candidate, page):
            continue
        final_url = page.get("final_url") or page.get("requested_url") or url
        host = (urlparse(final_url).hostname or "").lower().removeprefix("www.")
        if not host:
            continue
        if accepted_hosts and host not in accepted_hosts:
            continue
        accepted_hosts.add(host)
        captured.append({
            "candidate": candidate,
            "requested_url": page.get("requested_url", url),
            "final_url": final_url,
            "status": "inspected",
            "title": page.get("title", ""),
            "description": page.get("description", ""),
            "text_excerpt": page.get("text_excerpt", "")[:6500],
            "source_scope": "Candidate-matched same-host public product/content page; ownership not independently authenticated"
        })

        # Queue only same-host internal links with product-information intent.
        base_host = (urlparse(final_url).hostname or "").lower().removeprefix("www.")
        for href, anchor_text in page.get("links", []):
            absolute = urljoin(final_url, href)
            parsed = urlparse(absolute)
            link_host = (parsed.hostname or "").lower().removeprefix("www.")
            if parsed.scheme not in ("http", "https") or link_host != base_host:
                continue
            label = f"{parsed.path} {anchor_text}".casefold()
            if not any(term.replace("_", "-") in label or term in label for term in CONTENT_PAGE_KEYWORDS):
                continue
            if absolute not in queued and absolute not in visited:
                queued.add(absolute)
                queue.append(absolute)
                if len(queue) >= 40:
                    break

    return {
        "status": "inspected" if captured else "no_product_pages_captured",
        "pages_inspected": len(captured),
        "pages": captured,
        "crawl_limits": {"maximum_pages": max_pages, "same_host_only": True, "javascript_execution": False},
        "note": "Captured public page text is source material for original drafting, not permission to copy text verbatim or proof of legal domain ownership. Each factual claim remains subject to evidence review and human approval."
    }



def _normalized_claim_tokens(value):
    """Normalize meaningful claim terms for conservative matching to public copy."""
    value = re.sub(r"\[SOURCE VERIFICATION REQUIRED\]", "", str(value or ""), flags=re.I)
    tokens = re.findall(r"[a-z0-9]{3,}", value.casefold())
    stop = {
        "the", "and", "for", "with", "from", "that", "this", "these", "those",
        "are", "is", "was", "were", "has", "have", "had", "will", "would",
        "can", "could", "may", "might", "must", "should", "not", "but", "also",
        "into", "onto", "than", "then", "when", "where", "which", "while",
        "their", "there", "they", "them", "your", "you", "our", "its", "about",
        "based", "according", "page", "pages", "source", "sources", "claim",
        "claims", "states", "stated", "shows", "shown", "provides", "offers"
    }
    return set(token for token in tokens if token not in stop)


def quarantine_unclear_public_claims(content, semantic_review):
    """Preserve unclear claims for editorial review; remove only clear contradictions.

    An AI verdict of ``unclear`` means that the available excerpts do not
    conclusively establish the wording. It is not evidence that the statement
    is false. Therefore unclear sentences remain in this pre-publication draft
    and are listed for human review. Only claims explicitly marked
    ``contradicted`` may be removed, and only when a high-confidence sentence
    match is found. Publishing remains blocked while any unclear/contradicted
    claims remain unresolved.
    """
    from difflib import SequenceMatcher

    public_text = str(content or "").strip()
    review_items = []
    claims = (semantic_review or {}).get("claims", []) if isinstance(semantic_review, dict) else []
    unclear = [
        item for item in claims
        if isinstance(item, dict)
        and str(item.get("verdict", "")).casefold() == "unclear"
        and str(item.get("claim", "")).strip()
    ]
    contradicted = [
        item for item in claims
        if isinstance(item, dict) and str(item.get("verdict", "")).casefold() == "contradicted"
        and len(_normalized_claim_tokens(item.get("claim", ""))) >= 3
    ]

    for item in unclear:
        review_items.append({
            "claim_id": item.get("claim_id"),
            "claim": str(item.get("claim", "")).strip()[:900],
            "ai_screen_verdict": "unclear",
            "status": "retained_pending_human_review",
            "reason": "The source excerpts do not conclusively establish this wording. It is retained in the draft for human confirmation, not treated as false."
        })

    if not public_text or not contradicted:
        return _clean_public_markdown(public_text), review_items

    paragraphs = re.split(r"(\n\s*\n)", public_text)
    sentence_records = []
    for pi in range(0, len(paragraphs), 2):
        para = paragraphs[pi]
        if not para.strip():
            continue
        sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9#*_])", para)
        for si, sentence in enumerate(sentences):
            tokens = _normalized_claim_tokens(sentence)
            if tokens:
                sentence_records.append({
                    "paragraph_index": pi,
                    "sentence_index": si,
                    "sentence": sentence,
                    "tokens": tokens,
                })

    remove_keys = set()
    for item in contradicted:
        claim = str(item.get("claim", "")).strip()
        c_tokens = _normalized_claim_tokens(claim)
        scored = []
        for record in sentence_records:
            overlap = len(c_tokens & record["tokens"])
            coverage = overlap / max(1, len(c_tokens))
            precision = overlap / max(1, len(record["tokens"]))
            score = (0.72 * coverage) + (0.18 * precision) + (
                0.10 * SequenceMatcher(None, claim.casefold(), record["sentence"].casefold()).ratio()
            )
            scored.append((score, coverage, overlap, record))
        scored.sort(key=lambda row: (row[0], row[1], row[2]), reverse=True)
        if not scored:
            review_items.append({
                "claim_id": item.get("claim_id"), "claim": claim[:900],
                "ai_screen_verdict": "contradicted", "status": "manual_correction_required",
                "reason": "The contradicted claim could not be mapped confidently to one public sentence; manual correction is required."
            })
            continue
        best_score, best_coverage, best_overlap, best = scored[0]
        if best_overlap >= 3 and best_coverage >= 0.62 and best_score >= 0.52:
            remove_keys.add((best["paragraph_index"], best["sentence_index"]))
            review_items.append({
                "claim_id": item.get("claim_id"), "claim": claim[:900],
                "removed_text": best["sentence"].strip()[:900],
                "ai_screen_verdict": "contradicted", "status": "contradicted_sentence_removed",
                "reason": "A high-confidence sentence match was removed because the captured excerpts directly contradicted it. Human correction/review is still required."
            })
        else:
            review_items.append({
                "claim_id": item.get("claim_id"), "claim": claim[:900],
                "ai_screen_verdict": "contradicted", "status": "manual_correction_required",
                "reason": "The contradicted claim could not be matched to public copy with sufficient confidence; nothing was deleted automatically."
            })

    for pi in range(0, len(paragraphs), 2):
        para = paragraphs[pi]
        if not para.strip():
            continue
        sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z0-9#*_])", para)
        paragraphs[pi] = " ".join(
            sentence.strip() for si, sentence in enumerate(sentences)
            if (pi, si) not in remove_keys and sentence.strip()
        )

    return _clean_public_markdown("".join(paragraphs)), review_items


def _clean_public_markdown(value):
    """Remove empty Markdown structures and collapse duplicate blank lines."""
    text = str(value or "")
    text = re.sub(r"(?m)^\s*[-*+]\s*$", "", text)
    text = re.sub(r"(?m)^\s*\d+[.)]\s*$", "", text)
    text = re.sub(r"(?m)^\s*#{1,6}\s*(?:FAQ|Frequently Asked Questions)?\s*$", "", text, flags=re.I)
    text = re.sub(r"(?m)^\s*(?:Q:|Question:)\s*$", "", text, flags=re.I)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _is_sentence_like_markdown_heading(title):
    """Detect explanatory prose accidentally emitted with Markdown heading marks."""
    value = re.sub(r"[*_`]+", "", str(title or "")).strip()
    words = re.findall(r"\b[\w'-]+\b", value)
    return bool(
        len(value) >= 100
        or len(words) >= 16
        or re.search(r"[.!?]\s+\w", value)
        or value.endswith((".", "?", "!"))
    )


def remove_empty_markdown_headings(value):
    """Remove genuinely empty headings without discarding prose disguised as a heading.

    When a generated heading contains a complete explanatory sentence or a long
    source-backed statement, convert it into a normal paragraph. Short headings
    with no body are removed. No non-empty heading text is silently discarded.
    """
    lines = str(value or "").splitlines()
    output = []
    removed = []
    i = 0
    while i < len(lines):
        line = lines[i]
        match = re.match(r"^\s{0,3}(#{1,6})\s+(.+?)\s*$", line)
        if not match:
            output.append(line)
            i += 1
            continue

        title = match.group(2).strip()
        if _is_sentence_like_markdown_heading(title):
            # Explanatory prose is never a heading, regardless of whether a body follows.
            output.append(title)
            i += 1
            continue

        j = i + 1
        while j < len(lines) and not lines[j].strip():
            j += 1
        next_is_heading_or_end = (
            j >= len(lines) or bool(re.match(r"^\s{0,3}#{1,6}\s+\S", lines[j]))
        )
        if next_is_heading_or_end:
            removed.append(line.strip())
            i += 1
            continue

        output.append(line)
        i += 1

    cleaned = re.sub(r"\n{3,}", "\n\n", "\n".join(output)).strip()
    return cleaned, removed


def audit_public_article_structure(content, content_type="", site_scan=None):
    """Deterministic structural and scanned-feature coverage checks for a draft."""
    text = str(content or "").strip()
    lines = text.splitlines()
    headings = []
    empty_headings = []
    for line in lines:
        m = re.match(r"^\s{0,3}(#{1,6})\s*(.*?)\s*$", line)
        if not m:
            continue
        title = re.sub(r"[*_`]+", "", m.group(2)).strip()
        if not title:
            empty_headings.append(line.strip())
        else:
            headings.append((len(m.group(1)), title))

    h1_count = sum(1 for level, _ in headings if level == 1)
    h2_count = sum(1 for level, _ in headings if level == 2)
    h2_h3_section_count = sum(1 for level, _ in headings if level in (2, 3))
    normalized_titles = [re.sub(r"\s+", " ", title).casefold() for _, title in headings]
    duplicate_headings = sorted({title for title in normalized_titles if normalized_titles.count(title) > 1})
    words = re.findall(r"\b[\w'-]+\b", text)
    word_count = len(words)

    # Include numbered explanatory paragraphs, not only Markdown heading lines.
    numbered_markers = []
    for line in lines:
        candidate = line.strip()
        if candidate.startswith("#"):
            candidate = re.sub(r"^#{1,6}\s*", "", candidate)
        m = re.match(r"^(\d{1,2})[.)]\s+(.+)$", candidate)
        is_markdown_heading = line.lstrip().startswith("#")
        if m and (is_markdown_heading or len(re.findall(r"\b[\w'-]+\b", m.group(2))) >= 8):
            numbered_markers.append(int(m.group(1)))
    unique_markers = []
    for value in numbered_markers:
        if value not in unique_markers:
            unique_markers.append(value)
    numbering_gaps = []
    if len(unique_markers) >= 3 and len(unique_markers) == len(set(unique_markers)):
        expected = list(range(min(unique_markers), max(unique_markers) + 1))
        numbering_gaps = [value for value in expected if value not in unique_markers]

    normalized_content_type = str(content_type or "").strip().casefold()
    long_form = normalized_content_type in {
        "seo article", "seo blog post", "product review", "comparison", "landing page"
    }
    product_review_type = normalized_content_type in {
        "seo article", "seo blog post", "product review", "comparison"
    }

    feature_aliases = {
        "Frase Answers": ("frase answers", "answers widget", "conversational widget"),
        "SEO Research": ("seo research", "content brief", "research brief", "serp analysis"),
        "Topic Clusters": ("topic cluster", "topic map", "pillar page", "topical authority"),
        "Brand Voice": ("brand voice", "voice profile", "writing voice"),
        "SEO Content Optimization": ("content optimization", "seo optimization", "seo score"),
        "GEO Content Optimization": ("geo optimization", "geo score", "generative engine optimization", "ai search optimization"),
    }
    inspected_feature_names = []
    for page in ((site_scan or {}).get("pages", []) if isinstance(site_scan, dict) else []):
        if not isinstance(page, dict) or page.get("status") != "inspected":
            continue
        path = (urlparse(str(page.get("final_url") or page.get("requested_url") or "")).path or "").casefold()
        if "/features/" not in path:
            continue
        slug = path.rstrip("/").split("/")[-1]
        lookup = {
            "answers": "Frase Answers",
            "seo-research": "SEO Research",
            "clusters": "Topic Clusters",
            "brand-voice": "Brand Voice",
            "seo-content-optimization": "SEO Content Optimization",
            "geo-content-optimization": "GEO Content Optimization",
        }
        feature_name = lookup.get(slug)
        if feature_name and feature_name not in inspected_feature_names:
            inspected_feature_names.append(feature_name)

    lower_text = text.casefold()
    feature_coverage = []
    for feature_name in inspected_feature_names:
        aliases = feature_aliases.get(feature_name, (feature_name.casefold(),))
        covered = any(alias in lower_text for alias in aliases)
        feature_coverage.append({"feature": feature_name, "covered_in_public_content": covered})
    missing_features = [item["feature"] for item in feature_coverage if not item["covered_in_public_content"]] if long_form else []
    if not long_form:
        feature_coverage = []

    feature_rich_scan = len(inspected_feature_names) >= 4
    minimum_word_target = (
        350 if normalized_content_type == "landing page" else
        650 if product_review_type and feature_rich_scan else
        450 if long_form else 0
    )
    issues = []
    if not text:
        issues.append("Public article content is empty.")
    if long_form and h1_count != 1:
        issues.append(f"Expected exactly one H1 heading; found {h1_count}.")
    minimum_sections = 3 if normalized_content_type == "landing page" else 4
    if long_form and h2_h3_section_count < minimum_sections:
        issues.append(f"Expected at least {minimum_sections} H2/H3 content sections for this asset; found {h2_h3_section_count}.")
    if long_form and word_count < minimum_word_target:
        issues.append(f"Draft is short ({word_count} words); target at least {minimum_word_target} words based on the requested content type and scanned evidence, unless the source evidence genuinely limits coverage.")
    if empty_headings:
        issues.append("One or more empty Markdown headings remain.")
    if duplicate_headings:
        issues.append("Duplicate headings remain: " + ", ".join(duplicate_headings[:5]))
    if numbering_gaps:
        issues.append("Numbered feature sections appear to have gaps: " + ", ".join(map(str, numbering_gaps)) + ".")
    if missing_features:
        issues.append("Scanned product-feature pages are not represented in the public article: " + ", ".join(missing_features) + ".")

    return {
        "status": "review_required" if issues else "passed",
        "word_count": word_count,
        "minimum_word_target": minimum_word_target,
        "h1_count": h1_count,
        "h2_count": h2_count,
        "h2_h3_section_count": h2_h3_section_count,
        "heading_count": len(headings),
        "empty_headings": empty_headings,
        "duplicate_headings": duplicate_headings,
        "numbered_section_markers": unique_markers,
        "numbering_gaps": numbering_gaps,
        "official_feature_coverage": feature_coverage,
        "missing_official_features": missing_features,
        "issues": issues,
        "note": "Structure and feature coverage are completeness checks only. They do not prove factual accuracy, hands-on product experience, SEO performance, or commercial results. Unclear claims remain blocked for human review."
    }


def clean_internal_review(internal_review):
    """Tidy empty bullets, repeated sentences, duplicate notes and placeholders."""
    text = str(internal_review or "")
    repeated_note = (
        "Affiliate program terms have not been independently verified; confirm commission, "
        "payout and cookie details directly with the provider before publication."
    )
    text = re.sub(
        rf"(?:{re.escape(repeated_note)}\s*){{2,}}",
        repeated_note + " ", text, flags=re.I
    )
    text = re.sub(r"(?m)^(\s*\d+\.)\s*", r"\1 ", text)
    lines = []
    previous = None
    for raw in text.splitlines():
        line = raw.rstrip()
        if re.match(r"^\s*(?:[-*+]\s*|\d+[.)]\s*)$", line):
            continue
        if re.match(r"^\s*(?:FAQ|Frequently Asked Questions)\s*:?\s*$", line, re.I):
            continue
        key = re.sub(r"\s+", " ", line).strip().casefold()
        if key and key == previous:
            continue
        lines.append(line)
        if key:
            previous = key
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()

def harmonize_internal_review_metadata(internal_review, seo_package):
    """Replace stale generated meta-description lines in the internal review.

    The structured SEO package is authoritative for the current draft. Preserve
    the rest of the internal checklist and never leave an older risky snippet.
    """
    text = str(internal_review or "")
    safe_meta = str((seo_package or {}).get("meta_description", "")).strip()
    if not safe_meta:
        return text
    lines = text.splitlines()
    output = []
    replaced = False
    for line in lines:
        if re.search(r"(?i)^\s*(?:[-*]\s*)?(?:meta\s+description|suggested\s+meta\s+description)\s*:", line):
            output.append("Meta description: " + safe_meta)
            replaced = True
        else:
            output.append(line)
    if not replaced and re.search(r"(?i)\bmeta\s+description\b", text):
        # Avoid guessing the structure of a paragraph; append an explicit current value.
        output.append("\nCurrent audience-facing meta description: " + safe_meta)
    return "\n".join(output)


def run_content_creation_agent(request: ContentCreationRequest):
    """Create a sourced content asset, isolate public copy, and keep all publishing human-gated."""
    workflow = request.workflow_result
    if workflow.get("status") != "success":
        raise HTTPException(
            status_code=400,
            detail="Content creation requires a completed workflow with status='success'. Partial research cannot be used as final content evidence."
        )

    tracking_url = _validate_user_tracking_url(request.affiliate_tracking_url)
    records = workflow.get("structured_evidence_records") or []
    selected = next(
        (item for item in records
         if str(item.get("candidate", "")).strip().casefold() == request.candidate.strip().casefold()),
        None
    )
    if not selected:
        raise HTTPException(
            status_code=404,
            detail="The selected candidate was not found in this workflow's structured evidence ledger. Use the exact candidate name from the workflow result."
        )

    agents = workflow.get("agents") or {}
    verification = (agents.get("verification") or {}).get("report", "")
